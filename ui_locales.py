def normalize_language(value: str | None) -> str:
    """Accept ISO language/locale forms, with a predictable English fallback."""
    code = str(value or "en").lower().replace("_", "-").split("-", 1)[0]
    return "uk" if code in {"uk", "ua"} else "en"


def tr(language: str, key: str, **kwargs: object) -> str:
    text = UK.get(key, key) if normalize_language(language) == "uk" else key
    return text.format(**kwargs) if kwargs else text


def localize_explanation(message: str) -> str:
    """Translate known ranker prose without changing keyword-group names."""
